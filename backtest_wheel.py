#!/usr/bin/env python3
"""Backtest a wheel against historical NZ Lotto draws.

Reads a wheel file (generated by key_number_wheel.py or wheel_generator.py)
and calculates how many prizes the wheel would have won if played every draw.

Usage:
    python backtest_wheel.py --wheel key_wheel_pb1.txt
    python backtest_wheel.py --wheel wheel_hot_8.txt
"""

import argparse
import sqlite3
import sys
from collections import defaultdict
from pathlib import Path

DB_PATH = Path.cwd() / "data" / "lotto.db"


def parse_ticket_line(line: str):
    """Parse a line like '  1  2 16 22 27 33  PB:1' -> (numbers, powerball)"""
    parts = line.strip().split()
    if not parts:
        return None, None
    numbers = []
    powerball = None
    i = 0
    while i < len(parts):
        token = parts[i]
        if token.upper().startswith("PB:"):
            powerball = int(token.split(":")[1])
            i += 1
        elif token.isdigit():
            numbers.append(int(token))
            i += 1
        else:
            i += 1
    if len(numbers) != 6:
        return None, None
    return tuple(sorted(numbers)), powerball


def load_wheel(filepath: Path):
    tickets = []
    with open(filepath, encoding="utf-8") as f:
        for line in f:
            nums, pb = parse_ticket_line(line)
            if nums is not None:
                tickets.append((nums, pb))
    return tickets


def backtest(tickets):
    conn = sqlite3.connect(str(DB_PATH.resolve()), timeout=10)
    rows = conn.execute(
        "SELECT draw_number, draw_date, numbers, bonus, powerball FROM draws"
    ).fetchall()
    conn.close()

    # Prize category counts: (main_matches, bonus_matched) -> count
    prize_counts = defaultdict(int)
    # Also track how many draws produced at least one winning ticket
    draws_with_win = 0
    total_draws = len(rows)

    for _draw_num, _draw_date, nums_str, bonus, _powerball in rows:
        drawn_set = {int(x) for x in nums_str.split(",")}
        max_main = 0
        best_bonus_matched = False
        for ticket_nums, _ticket_pb in tickets:
            main_matches = len(set(ticket_nums) & drawn_set)
            bonus_matched = bonus in ticket_nums
            # Track best result for this draw across all tickets
            if main_matches > max_main:
                max_main = main_matches
                best_bonus_matched = bonus_matched
            elif main_matches == max_main:
                best_bonus_matched = best_bonus_matched or bonus_matched
            # Count prize if main_matches >= 3 or (main_matches == 2 and bonus_matched? no that doesn't win)
            # Standard NZ Lotto divisions:
            # 6 = Div1
            # 5+bonus = Div2
            # 5 = Div3
            # 4+bonus = Div4
            # 4 = Div5
            # 3+bonus = Div6
            # 3 = Div7
            if main_matches == 6:
                prize_counts["6"] += 1
            elif main_matches == 5 and bonus_matched:
                prize_counts["5+bonus"] += 1
            elif main_matches == 5:
                prize_counts["5"] += 1
            elif main_matches == 4 and bonus_matched:
                prize_counts["4+bonus"] += 1
            elif main_matches == 4:
                prize_counts["4"] += 1
            elif main_matches == 3 and bonus_matched:
                prize_counts["3+bonus"] += 1
            elif main_matches == 3:
                prize_counts["3"] += 1
        if max_main >= 3:
            draws_with_win += 1

    print(f"Backtested {len(tickets)} tickets against {total_draws} draws")
    print(f"Draws with at least one winning ticket (match ≥3): {draws_with_win}")
    print("\nPrize category counts (assuming you played all tickets every draw):")
    for cat in ["6", "5+bonus", "5", "4+bonus", "4", "3+bonus", "3"]:
        count = prize_counts.get(cat, 0)
        print(f"  {cat:8s}: {count}")

    total_spend = len(tickets) * 0.70 * total_draws
    print(f"\nTotal spend if played every draw: ${total_spend:,.2f}")
    print("(Actual prize amounts vary; you can look up historical division payouts.)")


def main() -> int:
    parser = argparse.ArgumentParser(description="Backtest a wheel file")
    parser.add_argument("--wheel", type=str, required=True, help="Path to wheel .txt file")
    args = parser.parse_args()

    wheel_path = Path.cwd() / args.wheel
    if not wheel_path.exists():
        print(f"File not found: {wheel_path}")
        return 1

    tickets = load_wheel(wheel_path)
    if not tickets:
        print("No tickets parsed from file.")
        return 1

    print(f"Loaded {len(tickets)} tickets from {wheel_path.name}")
    backtest(tickets)
    return 0


if __name__ == "__main__":
    sys.exit(main())
